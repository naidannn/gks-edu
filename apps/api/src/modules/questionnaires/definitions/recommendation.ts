const TEACHER_INTRO =
  'Доорх асуултуудад монголоор, товч бөгөөд тодорхой хариулна уу. Боломжтой бол бодит үйлдэл, амжилт, зан чанарыг харуулсан 1–2 жишээ дурдана уу — ерөнхий магтаалаас бодит жишээ хамаагүй хүчтэй. Таны хариултад үндэслэн GKS EDU төв англи хэл дээрх Recommendation Letter-ийг бэлтгээд, танд гарын үсэг зуруулахаар авчирна.';

function recommenderFields(extended: boolean): RecommenderField[] {
  return [
    { id: 'name', label: 'Овог, нэр', required: true },
    { id: 'position', label: extended ? 'Албан тушаал / академик цол' : 'Албан тушаал', required: true },
    { id: 'institution', label: 'Сургууль / байгууллага', required: true },
    ...(extended ? [{ id: 'department', label: 'Тэнхим / салбар' }] : []),
    { id: 'relation', label: 'Өргөдөл гаргагчтай ямар харилцаатай', placeholder: 'Жишээ: Математикийн багш, анги удирдсан' },
    ...(extended ? [{ id: 'yearsKnown', label: 'Хэдий хугацаанд мэдэх' }] : []),
    { id: 'email', label: 'И-мэйл', type: 'email', required: true },
    { id: 'phone', label: 'Утас', type: 'tel', required: true },
  ];
}

